    "    \"\"\"Long-short signal Sharpe (no TC, no sizing) = sign(pred) * actual / vol * sqrt(freq).\"\"\"\n"
    "    pnl = np.sign(y_pred) * y_true\n"
    "    return float(pnl.mean() / pnl.std() * np.sqrt(freq)) if pnl.std() > 0 else np.nan\n"
    "\n"
    "print('Setup complete.')"
